def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--runtime', required=True, type=Path)
    parser.add_argument('--java', default='java')
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix='price-orders-') as temp:
        directory = Path(temp)
        script = directory / 'ЦеновыеЗаказы.sbsl'
        script.write_text(allocation_source() + '\n' + publication_source() + '\n' + DRIVER)
        cmd = [args.java, '-Xmx256m', '--add-opens', 'java.base/java.lang=ALL-UNNAMED',
               '--add-opens', 'java.base/java.nio=ALL-UNNAMED', '-Dfile.encoding=UTF-8',
               f'-Djava.io.tmpdir={directory}', f'-Dlogs.root={directory / "logs"}',
               f'-Dexecutor.location={args.runtime}', f'-Dlogback.configurationFile={args.runtime / "config/logback.xml"}',
               '-cp', str(args.runtime / 'lib/*'), 'com.e1c.g5rt.executor.boot.ExecutorBootstrap',
               '-c', '10.0', str(script)]
        result = subprocess.run(cmd, cwd=directory, capture_output=True, text=True, timeout=60)
        print(result.stdout)
        if result.returncode:
            Path('/tmp/price-orders-failed.sbsl').write_text(script.read_text())
            print(result.stderr)
            raise SystemExit(result.returncode)


if __name__ == '__main__':
    main()
