def allocation_source():
    data = ROOT / 'dimkashelk/Игра/Данные'
    result = []
    for name in ('ПараметрыПродукта', 'ПредложениеРынка', 'СтрокаЗаказа', 'ИтогРынка'):
        fields = re.findall(r'- Имя: (.+)\n  Тип: (.+)', (data / (name + '.yaml')).read_text())
        result.append('структура ' + name + '\n' + '\n'.join('    пер ' + n + ': ' + t for n, t in fields) + '\n;')
    result.append('перечисление АлгоритмыРынка\n    ЦеновыеДоли,\n    СначалаДешевые\n;')
    result.append((data / 'ПроверкиДанных.xbsl').read_text())
    result.append((data.parent / 'Рынок/РасчетРынка.xbsl').read_text())
    source = '\n'.join(result).replace('ПроверкиДанных.', '')
    return re.sub(r'^импорт .+\n|^@[^\n]+\n', '', source, flags=re.M)


