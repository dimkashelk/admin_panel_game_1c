"""Original player authorization checks, including read-only finished OData games."""
import re
from test_erp_pull import EXCHANGE, method


def access_source():
    source = (EXCHANGE.parent / 'Данные/ДоступКабинета.xbsl').read_text()
    body = method(source, 'ПроверитьИгрока').replace('метод ПроверитьИгрока(', 'метод ПроверитьДоступКабинетаТеста(')
    body = body.replace('УчастникиИгры.Ссылка', 'КомандаДоступаТеста').replace('Игры.Ссылка', 'ИграДоступаТеста')
    body = body.replace('    исп КонтекстДоступа.Привилегированный()\n', '')
    body = body.replace('ДоступИгры.ТекущийПользователь()', '"player"').replace('ДоступИгры.ЭтоАдминистратор()', 'Ложь')
    body = body.replace('Участник.ЗагрузитьОбъект()', 'Участник').replace('Игра.ЗагрузитьОбъект()', 'Игра')
    body = body.replace('знч Команда = Участник', 'знч Команда: КомандаДоступаТеста? = Участник')
    body = body.replace('знч ОбъектИгры = Игра', 'знч ОбъектИгры: ИграДоступаТеста? = Игра')
    body, n = re.subn(r'Запрос\{ВЫБРАТЬ ПЕРВЫЕ 1 Пользователь ИЗ ИгрокиКоманд.*?\}\.Выполнить\(\)\.ПервыйИлиНеопределено\(\)',
                      'Участник.Назначен ? "player" : Неопределено', body, flags=re.S)
    assert n == 1, 'Player assignment query seam changed'
    body = body.replace('СостоянияИгры.Завершена', '"finished"').replace('СостоянияИгры.Отменена', '"cancelled"')
    return body + DRIVER


