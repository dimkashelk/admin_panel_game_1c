def price_phase_source():
    source = (EXCHANGE.parent / 'Управление/УправлениеИгрой.xbsl').read_text()
    body = method(source, 'СледующаяФазаЦеновыхЗаказов')
    body = body.replace('Игры.Объект', 'ИграТеста')
    body = body.replace('РынокЗаказов.ПроверитьЗавершение(', 'ПроверитьЗавершениеТеста(')
    body = body.replace('РынокЗаказов.СоздатьПерсональныеЗаказы(', 'СоздатьЦеновыеЗаказыТеста(')
    body = body.replace('    РынокЗаказов.ФиксироватьИтогиРаунда(Игра)\n', '')
    body = body.replace('ПараметрыДляПродукта(Игра, Правило.Продукт!)', 'новый ПараметрыФазыЦенТеста()')
    body = body.replace('ПараметрыПродукта', 'ПараметрыФазыЦенТеста')
    body = body.replace('Игра.ТекущийРаунд!.ЗагрузитьОбъект(Истина)!', 'Игра.ТекущийРаунд!')
    body = body.replace('Игра.ТекущийРаунд!.ЗагрузитьОбъект()!', 'Игра.ТекущийРаунд!')
    body = body.replace('    Раунд.Записать()\n', '')
    body = body.replace('СоздатьРаунд(', 'СоздатьРаундТеста(').replace('СохранитьПереход(', 'СохранитьПереходТеста(')
    for key, value in {'Подготовка': 'preparation', 'Ценообразование': 'pricing', 'СтартоваяПродажа': 'initial_sales',
                       'Продажи': 'sales', 'Анализ': 'analysis', 'Планирование': 'planning', 'Закупки': 'purchases', 'Производство': 'production'}.items():
        body = body.replace('ФазыИгры.' + key, '"' + value + '"')
    body = body.replace('СостоянияИгры.Завершена', '"finished"').replace('СостоянияФазы.Закрыта', '"closed"')
    return body + PHASE_DRIVER


