"""Execute original stock aggregation and player status with in-memory records."""
import re

from test_erp_pull import EXCHANGE, method


def stock_source():
    source = (EXCHANGE / 'РынокЗаказов.xbsl').read_text()
    body = '\n'.join(method(source, name) for name in ('ПредложениеВсехКоманд', 'СостояниеДанныхРынка'))
    body = body.replace('Игры.Объект', 'ИграОстатковТеста')
    body = body.replace('ПредложениеВсехКоманд(', 'ПредложениеОстатковТеста(')
    body = body.replace('СостояниеДанныхРынка(', 'СостояниеОстатковТеста(')
    body = body.replace('Игра.Ссылка', 'Игра').replace('Момент.Сейчас()', 'Игра.Время')
    body, count = re.subn(r'Запрос\{ВЫБРАТЬ Ссылка ИЗ УчастникиИгры.*?\}\.Выполнить\(\)',
                          'Игра.Команды', body, count=1, flags=re.S)
    assert count == 1, 'Stock team query seam changed'
    body = body.replace('Строка.Ссылка', 'Строка').replace('Участник.ЗагрузитьОбъект()!', 'Участник')
    body = body.replace('ДоступКабинета.Завершено(Участник, Раунд, Игра.ТокенФазы)', 'Участник.Завершено')
    body = body.replace('ОбменERP.Продукт(Код)', 'Код')
    body, count = re.subn(r'Запрос\{ВЫБРАТЬ Количество, ВремяПолучения, Статус ИЗ ЗаказыРынка.*?\}\.Выполнить\(\)',
                          'ЗаказыОстатковТеста(Участник, Продукт)', body, count=1, flags=re.S)
    assert count == 1, 'Stock reservation query seam changed'
    body = body.replace('Участник.Ид.ВСтроку()', 'Участник.Код')
    body = body.replace('ПродажиОткрыты(Игра)', 'Игра.ПродажиОткрыты')
    return body + DRIVER


