"""Native completion worker with only persistence and ERP transport replaced."""
import re
from test_erp_pull import EXCHANGE, method


def stage_order_source():
    source = (EXCHANGE / 'РынокЗаказов.xbsl').read_text()
    body = method(source, 'ЗакрытьВыполненныеЗаказы')
    body = body.replace('метод ЗакрытьВыполненныеЗаказы(', 'метод ЗакрытьЗаказыЭтапаТеста(')
    body = body.replace('УчастникиИгры.Ссылка', 'КомандаРезерва').replace('Игры.Ссылка', 'ИграРезерва')
    body = re.sub(r'^    исп КонтекстДоступа.+\n', '', body, flags=re.M)
    body = body.replace('СсылкаИгры.ЗагрузитьОбъект()!', 'СсылкаИгры')
    body, count = re.subn(r'Запрос\{ВЫБРАТЬ Ссылка ИЗ ЗаказыРынка.*?\}\.Выполнить\(\)',
                          'ЗаказыАвтозакрытияТеста(СсылкаИгры, Участник)', body, flags=re.S)
    assert count == 1
    body = body.replace('Строка.Ссылка', 'Строка')
    body, count = re.subn(r'            знч Команда = Участник\.ЗагрузитьОбъект.*?(?=            ПодтвердитьЗакрытие)',
                          '            знч Результат = АвтоОтветERPТеста(Заказ)\n', body, flags=re.S)
    assert count == 1
    body = body.replace('РезервироватьЗакрытие(', 'РезервироватьЗакрытиеТеста(')
    body = body.replace('ПодтвердитьЗакрытие(', 'ПодтвердитьЗакрытиеТеста(')
    body = body.replace('СостоянияИгры.Идет', '"running"')
    return body + DRIVER


