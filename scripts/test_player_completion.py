"""Execute original player completion and validation in the native XBSL test suite."""
import re
from test_erp_pull import EXCHANGE, method


def completion_source():
    cabinet = (EXCHANGE.parent / 'Управление/КабинетыИгроков.xbsl').read_text()
    market = (EXCHANGE / 'РынокЗаказов.xbsl').read_text()
    body = '\n'.join(method(cabinet, n) for n in
                     ('ЗавершитьЭтап', 'ПроверитьОткрытыйЭтап', 'ПроверитьУсловияЗавершения'))
    body += '\n' + method(market, 'СборПрайсЛистовОткрыт') + '\n' + method(market, 'ПроверитьПрайсЛист')
    for name in ('ЗавершитьЭтап', 'ПроверитьОткрытыйЭтап', 'ПроверитьУсловияЗавершения',
                 'СборПрайсЛистовОткрыт', 'ПроверитьПрайсЛист'):
        body = body.replace(name + '(', name + 'ЗавершенияТеста(')
    body = body.replace('Игры.Объект', 'ИграЗавершенияИгрока').replace('УчастникиИгры.Ссылка', 'КомандаЗавершенияИгрока')
    body = body.replace('ДоступИгры.ТекущийПользователь()', '"player"')
    body = body.replace('ДоступКабинета.ПроверитьИгрока(Участник)', 'ПроверитьДоступЗавершенияТеста(Участник)')
    body = body.replace('СсылкаИгры.ЗагрузитьОбъект()!', 'КопияИгрыЗавершенияТеста(СсылкаИгры)')
    body = body.replace('СсылкаИгры.ЗагрузитьОбъект(Истина)!', 'СсылкаИгры')
    body = re.sub(r'ДоступКабинета\.Завершено\(Участник, [^\n]+?\)', 'Участник.Завершено', body)
    body = re.sub(r'^    исп КонтекстДоступа.+\n', '', body, flags=re.M)
    body = body.replace('    исп Транзакции.Начать()', '    Участник.ВТранзакции = Истина')
    body = body.replace('РынокЗаказов.ПрочитатьПрайсЛистДляЗавершения', 'ПрочитатьЦеныЗавершенияТеста')
    body = body.replace('РынокЗаказов.ЗавершитьПоСроку(Игра)', 'ЗавершитьПоСрокуЗавершенияТеста(Участник)')
    body = body.replace('РынокЗаказов.ЗакрытьВыполненныеЗаказы(СсылкаИгры, Участник, Токен)', 'ТребоватьПроверку(не Участник.ВТранзакции, "Order closure under game lock")')
    body = body.replace('РынокЗаказов.', '')
    body = body.replace('Участник.ЗагрузитьОбъект(Истина)!', 'Участник')
    body = body.replace('        Команда.Записать()', '        Команда.ЗаписейЦен = Команда.ЗаписейЦен + 1')
    body, count = re.subn(r'    знч Записи = новый ЗаявленияКоманд.*?    Записи\.Записать\(\)',
                         '    Участник.Завершено = Истина\n    Участник.Заявлений = Участник.Заявлений + 1', body, flags=re.S)
    assert count == 1
    body, count = re.subn(r'Запрос\{ВЫБРАТЬ ПЕРВЫЕ 1 Ссылка ИЗ ЗаказыРынка.*?ПервыйИлиНеопределено\(\)',
                         '(Участник.ЕстьНепроведенные ? "pending" : Неопределено)', body, flags=re.S)
    assert count == 1
    body, count = re.subn(r'Запрос\{ВЫБРАТЬ Готов, ПоследнийСнимок, Ошибка ИЗ СостоянияУчастников.*?ПервыйИлиНеопределено\(\)',
                         'Участник.Готовность', body, flags=re.S)
    assert count == 1
    body = body.replace('ФактыERP.ПроверитьГотовностьИсполнения(Игра, Участник)',
                        'ТребоватьПроверку(Участник.ИсполнениеЗавершено, "Автоматическое исполнение не завершено")')
    body = body.replace('Правило.Продукт!.ЗагрузитьОбъект()!.Код', 'Правило.Код')
    body = body.replace('Игра.ТекущийРаунд!.ЗагрузитьОбъект()!.НомерРаунда', 'Игра.ТекущийРаунд!')
    body = body.replace('ПроверкиДанных.ЦелоеНеотрицательное', 'ЦелоеНеотрицательноеЦенТеста')
    body = body.replace('СостоянияИгры.Подготовка', '"preparation"').replace('СостоянияИгры.Идет', '"running"')
    body = body.replace('СостоянияФазы.Открыта', '"open"')
    return body + DRIVER


