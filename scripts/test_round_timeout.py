"""Timeout regressions used by test_market_odata.py (original XBSL, in-memory DB)."""
import re

from test_erp_pull import EXCHANGE, method


def timeout_source():
    source = (EXCHANGE / 'РынокЗаказов.xbsl').read_text()
    body = method(source, 'ЗавершитьПоСроку') + '\n' + method(source, 'ФиксироватьИтогиРаунда')
    body = body.replace('Игры.Объект', 'ИграГенерации').replace('Игра.Ссылка', 'Игра')
    body = body.replace('Момент.Сейчас()', 'Игра.Время')
    body, count = re.subn(r'Запрос\{ВЫБРАТЬ Ссылка ИЗ ЗаказыРынка.*?\}\.Выполнить\(\)',
                          'НезафиксированныеЗаказыТеста(Игра, Раунд)', body, flags=re.S)
    assert count == 1, 'Result freeze query seam changed'
    body = body.replace('Строка.Ссылка.ЗагрузитьОбъект(Истина)!', 'Строка')
    body = body.replace('        Заказ.Записать()\n', '')
    body, count = re.subn(r'Запрос\{ВЫБРАТЬ Ссылка ИЗ УчастникиИгры.*?\}\.Выполнить\(\)',
                          'АктивныеКомандыЗавершения(Игра)', body, flags=re.S)
    assert count == 1, 'Timeout team query seam changed'
    body = body.replace('ДоступКабинета.Завершено(Участник, Раунд, Токен)',
                        'ЗавершеноТеста(Игра, Участник, Раунд, Токен)')
    body = body.replace('новый ЗаявленияКоманд.НаборЗаписей()', 'новый НаборЗавершенияТеста(Игра = Игра)')
    body = re.sub(r'^        Записи\.Фильтр\.Установить\(.+\)\n', '', body, flags=re.M)
    body = body.replace('СостоянияИгры.Идет', '"running"').replace('СостоянияФазы.Открыта', '"open"')
    body = body.replace('ФазыИгры.СтартоваяПродажа', '"initial_sales"').replace('ФазыИгры.Продажи', '"sales"')
    return body + scheduler_source() + DRIVER


def scheduler_source():
    source = (EXCHANGE / 'КлиентERP.xbsl').read_text()
    body = method(source, 'ПланироватьФоновыйОбмен')
    body = body.replace('метод ПланироватьФоновыйОбмен()',
                        'метод ПланироватьЗавершениеТеста(Игры: ЧитаемыйМассив<ИграГенерации>, Сейчас: Момент)')
    body = re.sub(r'^    исп КонтекстДоступа.+\n|^    знч Сейчас = Момент.Сейчас\(\)\n', '', body, flags=re.M)
    body, count = re.subn(r'Запрос\{ВЫБРАТЬ Ссылка, Дедлайн ИЗ Игры.*?\}\.Выполнить\(\)',
                          'ИгрыПланировщикаТеста(Игры)', body, count=1, flags=re.S)
    assert count == 1, 'Scheduler deadline query seam changed'
    body, count = re.subn(r'Запрос\{ВЫБРАТЬ Ссылка, Игра ИЗ УчастникиИгры.*?\}\.Выполнить\(\)',
                          '<КомандаПланировщикаТеста>[]', body, count=1, flags=re.S)
    assert count == 1, 'Scheduler team query seam changed'
    body = body.replace('РынокЗаказов.Обновить', 'ОбновитьГенерацию')
    body = body.replace('Строка.Игра!.ЗагрузитьОбъект()!', 'Строка.Игра!')
    body = body.replace('ЕстьРаботаФоном', 'ЕстьРаботаПланировщикаТеста')
    return body.replace('ПланироватьКоманду', 'ПланироватьКомандуТеста')


